def analisar_pdf(ctx, pdf, titulos=(), blocos=False, max_png=60):
    import pymupdf
    doc = pymupdf.open(str(pdf))
    n = len(doc); ctx.info['paginas'] = n
    pasta = ctx.saida / 'paginas'; pasta.mkdir(exist_ok=True)
    pngs, textos, linhas_ultima = [], [], 0
    tn = [norm_ws(t).lower() for t in titulos if t]
    for i, page in enumerate(doc, 1):
        W, H = page.rect.width, page.rect.height
        txt = page.get_text('text'); textos.append(norm_ws(txt))
        bl = [b for b in page.get_text('blocks') if b[6] == 0 and b[4].strip()]
        imgs = page.get_image_info()
        if not txt.strip() and not imgs and not page.get_drawings():
            ctx.A('pagina-vazia', 'corrigir', f'p. {i}', 'página em branco')
        for b in bl:
            x0, y0, x1, y1 = b[:4]
            if x0 < 20 or x1 > W - 20 or y0 < 14 or y1 > H - 14:
                ctx.A('fora-da-margem', 'corrigir', f'p. {i}', f'texto encosta na borda da página (margem de {round(min(x0, W - x1, y0, H - y1))}pt): "{norm_ws(b[4])[:50]}"'); break
        try:
            spans = [s for blk in page.get_text('dict')['blocks'] if blk.get('type') == 0 for l in blk['lines'] for s in l['spans'] if s['text'].strip()]
            peq = [s for s in spans if s['size'] < 7]
            if peq: ctx.A('fonte-minuscula', 'nota', f'p. {i}', f'texto com {peq[0]["size"]:.1f}pt: "{peq[0]["text"][:40]}"')
        except Exception: pass
        for im in imgs:
            w_pt = im['bbox'][2] - im['bbox'][0]
            if w_pt > 60 and im.get('width') and im['width'] / (w_pt / 72) < 96:
                ctx.A('imagem-baixa-resolucao', 'nota', f'p. {i}', f'imagem com {round(im["width"] / (w_pt / 72))} dpi na página (abaixo de 96 dpi fica serrilhada)')
        if re.search(r'Erro!|Error!', txt):
            ctx.A('campo-com-erro', 'bloqueia', f'p. {i}', 'campo do Word com erro ("Erro! A origem da referência..."): atualize os campos ou refaça o sumário/referência')
        if bl and tn and i < n:
            ult = max(bl, key=lambda b: b[3]); t = norm_ws(ult[4]).lower()
            if any(t.startswith(x) and len(t) <= len(x) + 4 for x in tn):
                ctx.A('titulo-no-fim-da-pagina', 'corrigir', f'p. {i}', f'o título "{norm_ws(ult[4])[:50]}" é a última linha da página e o texto dele começa na seguinte (use "manter com o próximo")')
        if blocos:
            for b in bl:
                t = norm_ws(b[4].replace('-\n', ''))
                ctx.B(f'p. {i}', 'corpo' if palavras(t) >= 4 else 'rotulo', t)
        if i <= max_png:
            p = pasta / f'p-{i:02d}.png'
            page.get_pixmap(matrix=pymupdf.Matrix(0.85, 0.85)).save(str(p)); pngs.append(str(p))
        if i == n: linhas_ultima = len([l for l in txt.splitlines() if l.strip()])
    if n >= 2 and 0 < linhas_ultima <= 3:
        ctx.A('ultima-pagina-curta', 'nota', f'p. {n}', f'a última página tem só {linhas_ultima} linha(s): reduza o espaçamento ou corte para fechar na página anterior')
    ctx.paginas_texto = textos
    if pngs: folha(ctx, pngs, 'folha-documento', [f'p. {k + 1}' for k in range(len(pngs))], thumb=380, cols=4, por_folha=12)
    return pngs


def pagina_de(ctx, trecho):
    if not ctx.paginas_texto or not trecho: return None
    t = norm_ws(trecho)[:40].lower()
    if len(t) < 6: return None
    for i, p in enumerate(ctx.paginas_texto, 1):
        if t in p.lower(): return i
    return None
