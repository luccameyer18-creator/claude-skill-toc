@functools.lru_cache(maxsize=512)
def fonte(nome, px, negrito=False):
    from PIL import ImageFont
    reg, neg = FAM.get((nome or 'calibri').lower().strip(), FAM['arial'])
    for pasta in PASTAS_FONTES:
        p = pasta / (neg if negrito else reg)
        if p.exists():
            return ImageFont.truetype(str(p), max(6, int(round(px))))
    return ImageFont.load_default()


def quebrar(texto, f, largura):
    out = []
    for parte in re.split(r'[\n\x0b]', texto or ''):
        atual = ''
        for w in parte.split(' '):
            tent = (atual + ' ' + w) if atual else w
            if not atual or f.getlength(tent) <= largura: atual = tent
            else: out.append(atual); atual = w
        out.append(atual)
    return out


def luminancia(c):
    def lin(v):
        v /= 255
        return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
    return 0.2126 * lin(c[0]) + 0.7152 * lin(c[1]) + 0.0722 * lin(c[2])


def razao(a, b):
    x, y = luminancia(a), luminancia(b)
    return (max(x, y) + 0.05) / (min(x, y) + 0.05)


# ---------- folhas de fotos ----------
def folha(ctx, pngs, prefixo, rotulos=None, thumb=400, cols=3, por_folha=9):
    from PIL import Image, ImageDraw
    feitos = []
    for k in range(0, len(pngs), por_folha):
        ims = []
        for p in pngs[k:k + por_folha]:
            im = Image.open(p).convert('RGB'); r = thumb / im.width
            ims.append(im.resize((thumb, max(1, int(im.height * r)))))
        linhas = [ims[j:j + cols] for j in range(0, len(ims), cols)]
        alturas = [max(i.height for i in l) + 18 for l in linhas]
        folha_ = Image.new('RGB', (cols * (thumb + 8) + 8, sum(alturas) + 8), (27, 27, 27)); d = ImageDraw.Draw(folha_)
        y, n = 8, k
        for l, a in zip(linhas, alturas):
            x = 8
            for im in l:
                folha_.paste(im, (x, y)); d.text((x, y + im.height + 3), (rotulos[n] if rotulos else str(n + 1)), fill=(220, 220, 220))
                x += thumb + 8; n += 1
            y += a
        nome = f'{prefixo}-{k // por_folha + 1}.jpg'
        folha_.save(ctx.saida / nome, quality=80)
        feitos.append(nome)
    ctx.folhas += feitos
    return feitos


# ---------- Word (corretor e PDF) ----------
@contextlib.contextmanager
def word():
    import pythoncom, win32com.client
    pythoncom.CoInitialize()
    w = win32com.client.DispatchEx('Word.Application')  # instância nova: não mexe no Word aberto do usuário
    w.Visible = False; w.DisplayAlerts = 0
    try:
        yield w
    finally:
        try: w.Quit(0)
        except Exception: pass


LANG = {'pt-br': 1046, 'pt': 1046, 'pt-pt': 2070, 'en': 1033, 'en-us': 1033, 'en-gb': 2057, 'es': 3082, 'es-es': 3082}


def ortografia(ctx):
    """Corretor do Word sobre o texto extraído. Nomes próprios (maiúscula no meio da frase), siglas e palavras que
    aparecem 3 vezes ou mais (termos do assunto) ficam de fora; palavrasOk do contrato também."""
    if ctx.opc.get('ortografia') is False or not ctx.blocos: return
    idioma = str(ctx.opc.get('idioma') or 'pt-BR').lower()
    lid = LANG.get(idioma) or LANG.get(idioma.split('-')[0], 1046)
    ok = {str(x).lower() for x in ctx.opc.get('palavrasOk', [])}
    cont, onde_de = Counter(), {}
    for b in ctx.blocos:
        t = SEM_LINK.sub(' ', b['texto'])
        for m in re.finditer(r"[^\W\d_]{3,}(?:[-'’][^\W\d_]+)*", t):
            w, ant = m.group(0), t[:m.start()].rstrip()
            inicio = (not ant) or ant[-1] in '.!?:;\n•-–—'
            if w[0].isupper() and not inicio: continue
            if w.isupper() or re.search(r'[a-zà-ú][A-ZÀ-Ú]', w): continue
            k = w.lower(); cont[k] += 1; onde_de.setdefault(k, b['onde'])
    cand = [w for w, n in cont.items() if n < 3 and w not in ok][:3000]
    if not cand: return
    try:
        with word() as w:
            d = w.Documents.Add()
            r = d.Content; r.Text = '\r'.join(cand); r.LanguageID = lid; r.NoProofing = False
            erros = []
            for i, e in enumerate(d.SpellingErrors, 1):
                if len(erros) >= 60: break
                t = e.Text
                try: sug = [s.Name for s in d.SpellingErrors(i).GetSpellingSuggestions()][:3]
                except Exception: sug = []
                erros.append((t, sug))
            d.Close(False)
        for t, sug in erros:
            ctx.A('ortografia', 'corrigir', onde_de.get(t.lower(), ''), f'"{t}" não está no dicionário do Word ({idioma})' + (f'; sugestão: {", ".join(sug)}' if sug else '') + '. Termo correto do assunto? Ponha em palavrasOk no contrato.')
    except Exception as e:
        ctx.aviso(f'ortografia não conferida (Word indisponível ou sem corretor): {type(e).__name__}: {str(e)[:120]}')


