CAP_PADRAO = 8
CAPS = {'ortografia': 25, 'texto-provisorio': 12}
SEM_LINK = re.compile(r'https?://\S+|\S+@\S+\.\S+|[\w.-]+\.(?:com|br|org|net|io|js|css|html|json|md|png|jpg|pdf|docx|xlsx|pptx)\b', re.I)
SUSPEITOS_META = re.compile(r'python-docx|python-pptx|openpyxl|anthropic|claude|openai|chatgpt|\bgpt\b|ai assistant|generated by|steve canny|^user$|^unknown$', re.I)


def palavras(t):
    return len(re.findall(r"[^\W\d_][\w'’-]*", t or ''))


def norm_ws(t):
    return re.sub(r'\s+', ' ', (t or '').replace('\u00ad', '')).strip()


class Ctx:
    def __init__(self, opc, saida):
        self.opc = opc or {}
        self.saida = Path(saida); self.saida.mkdir(parents=True, exist_ok=True)
        self.achados, self.blocos, self.avisos, self.folhas = [], [], [], []
        self.info = {}
        self._cont, self._extra = Counter(), {}
        self.paginas_texto = None

    @property
    def pt(self):
        return str(self.opc.get('idioma') or 'pt-BR').lower().startswith('pt')

    def A(self, regra, grav, onde, detalhe, busca=None, valor=None):
        n = self._cont[regra]; self._cont[regra] += 1
        if n >= CAPS.get(regra, CAP_PADRAO):
            e = self._extra.setdefault(regra, [grav, 0]); e[1] += 1
            return
        a = {'regra': regra, 'gravidade': grav, 'onde': onde, 'detalhe': detalhe, 'porDetalhe': True}
        if busca: a['_busca'] = busca
        if valor is not None: a['valor'] = valor
        self.achados.append(a)

    def B(self, onde, papel, texto, **kw):
        t = (texto or '').replace('\x0b', '\n').replace('\xa0', ' ').strip()
        if t: self.blocos.append({'onde': onde, 'papel': papel, 'texto': t, 'origem': 'documento', **kw})

    def aviso(self, s):
        self.avisos.append(s)

    def fechar(self):
        for regra, (g, n) in self._extra.items():
            self.achados.append({'regra': regra, 'gravidade': g, 'onde': '', 'detalhe': f'mais {n} ocorrência(s) de {regra} além das listadas', 'porDetalhe': True})


def tentar(ctx, rotulo, fn, *a, **kw):
    try:
        return fn(*a, **kw)
    except Exception as e:
        ctx.aviso(f'{rotulo}: {type(e).__name__}: {str(e)[:160]}')
        if os.environ.get('TOC_DEBUG'): traceback.print_exc()
        return None


